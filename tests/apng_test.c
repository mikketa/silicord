static int canvas_is(const unsigned char *c, const unsigned char *want)
{
    for (int i = 0; i < 16; i++)
        if (c[i] != want[i])
            return 0;
    return 1;
}

void entry(void)
{
    /* Premultiplied BGRA: red, green / blue, clear; then half-white over the clear pixel. */
    static const unsigned char first[16] = {0, 0, 255, 255, 0, 255, 0, 255, 255, 0, 0, 255, 0, 0, 0, 0};
    static const unsigned char second[16] = {0, 0, 255, 255, 0, 255, 0, 255, 255, 0, 0, 255, 128, 128, 128, 128};
    static const unsigned char png_only[8] = {0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n'};
    unsigned char canvas[16];
    apng_t *a = apng_open(k_apng, sizeof k_apng);
    unsigned w = 0, h = 0;

    check(a != NULL, "an animated PNG opens");
    if (a) {
        apng_size(a, &w, &h);
        check(w == 2 && h == 2 && apng_frames(a) == 2, "size and frame count");
        check(apng_next(a, canvas) == 100 && canvas_is(canvas, first), "first frame, unfiltered and premultiplied");
        check(apng_next(a, canvas) == 200 && canvas_is(canvas, second), "second frame blends over the first");
        check(apng_next(a, canvas) == 100 && canvas_is(canvas, first), "loops, clearing the disposed area");
        apng_free(a);
    }
    check(apng_open(png_only, sizeof png_only) == NULL, "a still PNG is left to WIC");
    finish();
}
