#!/usr/bin/env python3
"""Builds src/twemoji_data.c: the SVG Discord draws for each Unicode emoji.

Discord's web client (https://discord.com/app) ships Twemoji as hashed SVGs
under /assets/. Its main bundle (web.*.js) maps each file name ("1f44d-1f3fd")
to a module, and its emoji bundle (vnd-emoji.*.js) maps each module to the
asset ("/assets/<16 hex digits>.svg"). Keys are written without U+FE0F, which
Twemoji's names drop or keep from one emoji to the next: lookups strip it too.

Usage, from the repository root:  python tools/make_twemoji.py [web.js vnd-emoji.js]
"""
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = "https://discord.com/app"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")


def bundles(argv):
    if len(argv) == 3:
        return Path(argv[1]).read_text(encoding="utf-8", errors="replace"), Path(argv[2]).read_text(
            encoding="utf-8", errors="replace")
    page = get(APP)
    scripts = re.findall(r'/assets/[^"]+\.js', page)
    web = next(s for s in scripts if re.search(r"/web\.[0-9a-f]+\.js$", s))
    emoji = next(s for s in scripts if re.search(r"/vnd-emoji\.[0-9a-f]+\.js$", s))
    return get("https://discord.com" + web), get("https://discord.com" + emoji)


def utf16(cps):
    data = "".join(chr(c) for c in cps).encode("utf-16-le")
    return [int.from_bytes(data[i:i + 2], "little") for i in range(0, len(data), 2)]


def main():
    web, emoji = bundles(sys.argv)
    names = dict(re.findall(r'"\./([0-9a-f-]+)\.svg":"?(\d+)"?', web))
    assets = dict(re.findall(r'(\d+)\(e\)\{e\.exports="/assets/([0-9a-f]{16})\.svg"\}', emoji))
    if len(names) < 3000:
        sys.exit("make_twemoji: Discord's emoji file names were not found")
    table = {}
    for name, module in names.items():
        if module not in assets:
            continue
        key = tuple(utf16([int(c, 16) for c in name.split("-") if int(c, 16) != 0xFE0F]))
        if key in table:
            sys.exit(f"make_twemoji: {name} and another emoji are the same without U+FE0F")
        table[key] = assets[module]
    write_table(table)


def write_table(table):
    """src/twemoji_data.c from {UTF-16 units: asset as 16 hex digits}, in twemoji.h's layout."""
    keys = sorted(table)
    lines = [
        "/*",
        " * Discord's image of each Unicode emoji (Twemoji): the emoji in UTF-16 without",
        " * U+FE0F, and its SVG, https://discord.com/assets/<asset as 16 hex digits>.svg.",
        " * Sorted by code units. Generated by tools/make_twemoji.py from Discord's web client.",
        " */",
        '#include "twemoji.h"',
        "",
        "const wchar_t k_twemoji_text[] =",
    ]
    for key in keys:
        lines.append('    L"' + "".join(f"\\x{u:04X}" for u in key) + '"')
    lines[-1] += ";"
    ends, end = [], 0
    for key in keys:
        end += len(key)
        ends.append(str(end))
    if end > 0xFFFF:
        sys.exit("make_twemoji: the emoji no longer fit unsigned short offsets")
    lines.append("const unsigned short k_twemoji_end[] = {")
    lines += ["    " + ", ".join(ends[i:i + 16]) + "," for i in range(0, len(ends), 16)]
    lines += ["};", "const unsigned long long k_twemoji_asset[] = {"]
    assets = [f"0x{table[key]}ull" for key in keys]
    lines += ["    " + ", ".join(assets[i:i + 4]) + "," for i in range(0, len(assets), 4)]
    lines += ["};", f"const int k_ntwemoji = {len(keys)};", ""]
    out = ROOT / "src" / "twemoji_data.c"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {len(keys)} emoji")


if __name__ == "__main__":
    main()
